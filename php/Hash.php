<?php
// --- ส่วนการตั้งค่าและเตรียมข้อมูล ---

// เรียกใช้ไฟล์ auth.php ซึ่งอาจจะมีการตรวจสอบสิทธิ์การเข้าถึง (แม้ในสคริปต์นี้อาจไม่จำเป็น แต่เป็นแบบแผนที่ดี)

// เรียกใช้ไฟล์ db.php เพื่อเชื่อมต่อกับฐานข้อมูล ซึ่งจะสร้างตัวแปร $conn ขึ้นมา
require_once "db.php"; 

// กำหนดรหัสผ่านใหม่ที่ต้องการตั้งค่าในรูปแบบข้อความธรรมดา (Plain Text)
$password_plain = 'admin9876';

// ใช้ฟังก์ชัน password_hash() เพื่อเข้ารหัสรหัสผ่านด้านบนด้วยอัลกอริทึม BCRYPT ซึ่งเป็นวิธีที่ปลอดภัยและแนะนำในปัจจุบัน
// การเข้ารหัสนี้เป็นแบบทางเดียว (One-way) ไม่สามารถถอดรหัสกลับมาเป็นข้อความเดิมได้
$password_hash = password_hash($password_plain, PASSWORD_BCRYPT);

// แสดงผลรหัสผ่านที่ถูกเข้ารหัสแล้วออกมาทางหน้าจอ เพื่อให้เราสามารถคัดลอกไปใช้หรือเพื่อยืนยันว่าการเข้ารหัสทำงานถูกต้อง
echo "<h3>Generated bcrypt hash:</h3>";
echo "<pre>" . htmlspecialchars($password_hash) . "</pre>";

// กำหนดชื่อผู้ใช้ (username) ที่เราต้องการจะเปลี่ยนรหัสผ่าน
$username = 'admin';

// --- ส่วนการทำงานกับฐานข้อมูล ---

// ตรวจสอบว่าตัวแปร $conn ถูกสร้างขึ้นจากการ include ไฟล์ db.php และเป็นการเชื่อมต่อแบบ mysqli จริงๆ หรือไม่
// เป็นการป้องกันข้อผิดพลาดหากไฟล์ db.php มีปัญหา
if (!isset($conn) || !($conn instanceof mysqli)) {
    // หากไม่มีการเชื่อมต่อ ให้แสดงข้อความผิดพลาดและหยุดการทำงานของสคริปต์ทันที
    echo "<p style='color:red'>ERROR: db.php ไม่ได้สร้างตัวแปร \$conn หรือเชื่อมต่อไม่สำเร็จ.</p>";
    exit;
}

// เตรียมคำสั่ง SQL (Prepare Statement) สำหรับการอัปเดตข้อมูล
// การใช้ "?" เป็น placeholder เพื่อป้องกันการโจมตีแบบ SQL Injection
$stmt = $conn->prepare("UPDATE users SET password = ? WHERE username = ?");

// ตรวจสอบว่าการเตรียมคำสั่ง SQL สำเร็จหรือไม่ (อาจไม่สำเร็จหากพิมพ์ชื่อตารางหรือคอลัมน์ผิด)
if ($stmt === false) {
    // หากล้มเหลว ให้แสดงข้อผิดพลาดของฐานข้อมูลและหยุดการทำงาน
    echo "<p style='color:red'>Prepare failed: " . htmlspecialchars($conn->error) . "</p>";
    exit;
}

// นำตัวแปรมาผูกกับ placeholder (?) ในคำสั่ง SQL
// "ss" หมายถึงตัวแปรทั้ง 2 ตัวเป็นชนิด String (สตริง)
// ? ตัวแรกจะถูกแทนที่ด้วยค่าจาก $password_hash
// ? ตัวที่สองจะถูกแทนที่ด้วยค่าจาก $username
$stmt->bind_param("ss", $password_hash, $username);

// สั่งให้คำสั่ง SQL ที่เตรียมและผูกค่าไว้แล้วทำงาน (Execute)
$ok = $stmt->execute();

// ตรวจสอบผลลัพธ์ของการ execute
if ($ok) {
    // ถ้าสำเร็จ ให้แสดงข้อความยืนยัน
    echo "<p style='color:green'>อัปเดตรหัสผ่านของผู้ใช้ '{$username}' เรียบร้อยแล้ว</p>";
} else {
    // ถ้าล้มเหลว ให้แสดงข้อผิดพลาดที่เกิดขึ้น
    echo "<p style='color:red'>Execute failed: " . htmlspecialchars($stmt->error) . "</p>";
}

// --- ส่วนการปิดการเชื่อมต่อและคำเตือน ---

// ปิด statement ที่เตรียมไว้ เพื่อคืนทรัพยากรให้กับเซิร์ฟเวอร์
$stmt->close();
// ปิดการเชื่อมต่อฐานข้อมูล
$conn->close();

// แสดงคำเตือนที่สำคัญมาก: ไฟล์นี้ควรรีบลบทิ้งทันทีหลังจากใช้งานเสร็จ
echo "<p><strong>*** หลังยืนยันแล้วให้ลบไฟล์นี้ทันที (security) ***</strong></p>";
?>